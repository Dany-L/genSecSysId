class TestGateConfig:
    """The gate's settings must come from the checked-in YAML and survive loading.

    Guards two failure modes that are otherwise invisible: the config silently
    losing a field (unknown keys are dropped, not raised — grep a run log for
    "Ignoring unknown config field(s)"), and someone retuning the gate by editing
    the constants instead of the file that documents why they are what they are.
    """

    def test_the_settings_come_from_the_config_file(self):
        assert CONFIG_PATH.exists(), f"missing gate config: {CONFIG_PATH}"
        assert GATE_LR == CFG.optimizer.learning_rate
        assert GATE_REG == CFG.training.regularization_weight
        assert GATE_EPOCHS == CFG.training.max_epochs
        assert GATE_CLIP == CFG.training.gradient_clip_value
        assert WARMUP == CFG.training.warmup_steps

    def test_the_fields_the_gate_depends_on_survived_loading(self):
        """A dropped or renamed field would come back as the dataclass default and
        quietly change what the gate measures."""
        assert CFG.model.initialization.method == "warm_start"
        assert CFG.model.initialization.warm_start_units == "physical"
        assert CFG.model.initialization.warm_start_noise > 0.0
        assert CFG.training.gradient_clip_value is not None, (
            "gradient_clip_value went missing; without it a single gradient spike "
            "inflates Adam's second moment and freezes training"
        )
        assert CFG.training.solve_max_s_on_violation is True
        assert CFG.model.custom_params.get("learn_L") is True
        assert set(CFG.model.custom_params["structural_constraints"]) == {"D", "D12"}
        assert CFG.data.shuffle is False, "the gate must be deterministic"
        assert CFG.data.use_diverging_trajectories is True, (
            "the diverging variant of the gate must stay enabled"
        )

    def test_it_is_not_the_working_config(self):
        """The gate must not read genSecSysId-Data — that file is a live experiment
        and the gate is the fixed reference point it is checked against."""
        assert "genSecSysId-Data" not in str(CONFIG_PATH)
        assert CONFIG_PATH.is_relative_to(Path(__file__).parent)


class TestReferenceIsRecoverable:
    """Guards on the fixture itself. If these fail, the rest proves nothing."""

    def test_the_generating_parameters_fit_their_own_data(self, true_theta_loss):
        assert true_theta_loss < 1e-3, (
            f"the reference model does not reproduce its own data (loss "
            f"{true_theta_loss:.3g}); the fixture, not the trainer, is broken"
        )

    def test_the_dead_zone_actually_fires(self, sanity):
        """A reference whose nonlinearity never leaves the band would make this an
        LTI test, and Delta'(z) = 0 means no gradient reaches B2/C2/D21 at all."""
        _, _, _, _, _, _, _, rep = _warm_start(sanity, noise=0.0)
        assert rep.firing_rate is not None and rep.firing_rate > 0.0
        assert rep.max_abs_z > 1.0

    def test_warm_start_lands_on_the_reference_and_is_feasible(self, sanity):
        m, _, _, _, _, _, _, rep = _warm_start(sanity, noise=0.0)
        assert rep.constraints_satisfied and m.check_constraints()

    def test_a_perturbed_start_is_feasible_by_projection(self, sanity):
        """The projection's job: every draw starts inside the certified set."""
        for seed in range(4):
            m, _, _, _, _, _, _, rep = _warm_start(sanity, noise=0.01, seed=seed)
            assert rep.constraints_satisfied, f"seed {seed} started infeasible"
            assert m.check_constraints()


def _run_gate(sanity, true_theta_loss, tmp, variant, div_loader=None):
    """One warm-started training run, followed by the post-processing and
    evaluation stages a real run does, all logged to MLflow.

    Records the distance to the generating parameters before and after, because a
    falling loss is not by itself evidence of recovering the model.
    """
    m, tl, vl, tel, tdl, vdl, norm, rep = _warm_start(sanity, noise=0.002)
    div = tdl if div_loader else None
    su = float(np.asarray(norm.input_std).reshape(-1)[0])
    sy = float(np.asarray(norm.output_std).reshape(-1)[0])
    ref = sanity["ref"]
    true = {"A": ref["A"], "B": ref["B"] * su, "B2": ref["B2"],
            "C": ref["C"] / sy, "C2": ref["C2"]}

    def dist():
        num = sum(np.linalg.norm(getattr(m, k).detach().numpy() - v) ** 2
                  for k, v in true.items())
        den = sum(np.linalg.norm(v) ** 2 for v in true.values())
        return float(np.sqrt(num / den))

    start_loss, start_dist = _val_loss(m, vl), dist()
    params = {"variant": variant, "warm_start_noise": 0.002, "lr": GATE_LR,
              "regularization_weight": GATE_REG, "gradient_clip_value": GATE_CLIP,
              "epochs": GATE_EPOCHS, "nx": NX, "nw": NW, "warmup_steps": WARMUP,
              "use_diverging_trajectories": bool(div_loader),
              "config": CONFIG_PATH.name}
    artifacts = tmp / "artifacts"
    artifacts.mkdir(parents=True, exist_ok=True)

    with _mlflow_run(variant, params) as mlf:
        if mlf is not None:
            mlf.log_metric("true_theta_loss", true_theta_loss)
            mlf.log_metric("start_val_loss", start_loss)
            mlf.log_metric("start_dtheta", start_dist)
            for name, value in (rep.to_metrics() or {}).items():
                mlf.log_metric(f"initialization/{name}", float(value))
        history = _train(m, tl, vl, epochs=GATE_EPOCHS, lr=GATE_LR, tmp_path=tmp,
                         div_loader=div, mlf=mlf, extra_fn=lambda: {"dtheta": dist()})
        end = dist()

        # ---- post-processing: re-solve the certificate over the trained theta ----
        # The same call scripts/post_process.py makes. For a model that converged
        # back to the generator, the certificate it now admits should look like the
        # reference's — a check on the dynamics that does not go through the loss.
        post = m.post_process(n_grid=8, s_min=0.1, s_max=20.0)

        # ---- evaluation on the held-out split, WITH artifacts ----
        # save_files=True writes predictions/targets/inputs/states + the metrics
        # json, exactly as scripts/evaluate.py does, so the MLflow run carries the
        # same evidence a real run does rather than just scalars.
        ev = Evaluator(m, device="cpu", output_dir=str(artifacts / "evaluation"),
                       warmup_steps=WARMUP)
        results = ev.evaluate(tel, normalizer=norm, print_results=False, save_files=True)
        metrics = {k: v for k, v in results["metrics"].items()
                   if k != "per_step" and np.isscalar(v)}
        div_metrics = {}
        if vdl is not None:
            dres = ev.evaluate_diverging(vdl, normalizer=norm, print_results=False,
                                         save_files=True)
            div_metrics = {k: v for k, v in (dres.get("metrics_div") or {}).items()
                           if np.isscalar(v)}

        figures = _make_plots(m, vl, vdl, norm, artifacts, variant)

        if mlf is not None:
            for key in ("s_opt", "success", "constraints_satisfied"):
                if key in post and np.isscalar(post[key]):
                    mlf.log_metric(f"post_process/{key}", float(post[key]))
            for key, value in (post.get("max_s") or {}).items():
                if np.isscalar(value) and value is not None:
                    mlf.log_metric(f"post_process/max_s/{key}", float(value))
            for key, value in metrics.items():
                mlf.log_metric(f"test/{key}", float(value))
            for key, value in div_metrics.items():
                mlf.log_metric(f"test_div/{key}", float(value))
            best = min(v for _, v in history)
            mlf.log_metric("best_val_loss", best)
            mlf.log_metric("final_val_loss", history[-1][1])
            mlf.log_metric("end_dtheta", end)
            mlf.log_metric("best_over_true", best / max(true_theta_loss, 1e-30))
            mlf.set_tag("gate_passed", str(best < 10 * true_theta_loss))
            try:
                mlf.log_artifacts(str(artifacts), "outputs")
            except Exception:
                pass

    return {"model": m, "history": history, "start_loss": start_loss,
            "start_dist": start_dist, "end_dist": end, "post": post,
            "test_metrics": metrics, "test_div_metrics": div_metrics,
            "figures": figures, "artifacts": artifacts}


def _make_plots(m, vl, vdl, norm, artifacts, variant):
    """Prediction plots for the run, saved next to the evaluation artifacts.

    Uses the Trainer's own plotting so the figures match what a real run produces.
    Plotting is reporting, not the thing under test: a failure here is recorded and
    swallowed rather than failing the gate.
    """
    plots = artifacts / "plots"
    plots.mkdir(parents=True, exist_ok=True)
    made = []
    plotter = Trainer(
        model=m, train_loader=vl, val_loader=vl, val_div_loader=vdl,
        loss_fn=get_loss_function("mse"),
        optimizer=get_optimizer(m.parameters(), "adam", learning_rate=GATE_LR),
        warmup_steps=WARMUP, device="cpu", mlflow_tracking=False,
        output_dir=str(plots), model_dir=str(plots), log_dir=str(plots),
    )
    for fn, name in ((plotter.plot_trajectories, f"{variant}_predictions"),
                     (plotter.plot_trajectories_div, f"{variant}_predictions_div")):
        try:
            fn(normalizer=norm, name=name)
            made.extend(str(q) for q in plots.rglob(f"*{name}*"))
        except Exception as exc:
            made.append(f"FAILED {name}: {exc}")
    return made


