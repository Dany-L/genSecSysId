# Everything the gate runs at comes from a CHECKED-IN config, not from constants
# here and not from the working config in genSecSysId-Data. That file is a live
# experiment; the gate has to be a fixed reference point. Loading it through the
# real Config also means a renamed or dropped field fails the gate instead of being
# silently ignored.
CONFIG_PATH = Path(__file__).parent / "resoruces" / "sanity_gate.yaml"
CFG = Config.from_yaml(str(CONFIG_PATH))

ND, NE = 1, 1
NX, NW = CFG.model.nx, CFG.model.nw
TS = CFG.data.sampling_time
SEQ_LEN = CFG.data.train_sequence_length
WARMUP = CFG.training.warmup_steps

# Reference-system shape. Chosen so the fixture has the properties the gate needs —
# see _reference_system for what each one buys and how it was measured.
DAMPING = 2.0                 # -> rho(A) = 0.95
BP_LO, BP_HI = 0.05, 1.2      # dead-zone breakpoints, geometrically spaced
NL_GAIN, NL_POWER = 6.0, 3.0  # -> rho(A + B2 C2) = 1.14, escape outside the band
CONV_AMP, X0_AMP = 1.0, 0.2   # converging split: ~20% firing, no escapes
DIV_AMP = 4.0                 # diverging split: escapes from x0 = 0
DIVERGENCE_CAP = 50.0         # stop recording once the state clearly escapes;
                              # keeps max|y| ~50x the converging range, as in the
                              # real split (21.2 vs 0.555)
N_TRAJ, N_DIV_TRAJ, N_STEPS = 8, 6, 600


def _reference_system():
    """A Lure system that is stable in the dead band and UNSTABLE outside it.

    This is the structure that makes the whole exercise meaningful, and it mirrors
    the Duffing reference:

        rho(A)         = 0.95   -> inside the band the model is a damped oscillator
        rho(A + B2 C2) = 1.14   -> with the dead zone fully active it diverges

    (the Duffing reference is 0.9937 / 1.109). Without the second property no input
    could ever produce a diverging trajectory, and the diverging half of the gate
    would be vacuous — an earlier version of this fixture had rho(A + B2 C2) = 0.95
    and was silently globally stable.

    The nonlinearity is a staggered-breakpoint dead zone, again as in the Duffing
    model: unit i fires once |q| > bp_i, and its gain grows like bp_i^3, so the
    earliest-firing units barely perturb the dynamics while the late ones drive the
    escape. That graded structure is what lets ordinary trajectories exercise the
    nonlinearity (~20% of (step, unit) pairs fire) without being dragged out of the
    stable region.
    """
    bp = np.geomspace(BP_LO, BP_HI, NW)
    C2 = np.zeros((NW, NX)); C2[:, 0] = 1.0 / bp
    B2 = np.zeros((NX, NW)); B2[1, :] = TS * NL_GAIN * bp ** NL_POWER
    return {
        "A": np.eye(NX) + TS * np.array([[0.0, 1.0], [-1.0, -DAMPING]]),
        "B": TS * np.array([[0.0], [1.0]]),
        "B2": B2,
        "C": np.array([[1.0, 0.0]]),
        "C2": C2,
        "D": np.zeros((NE, ND)),
        "D12": np.zeros((NE, NW)),
        "D21": np.zeros((NW, ND)),
        "nx": NX, "nz": NW, "nu": ND, "ny": NE,
    }


def _simulate(ref, u, x0, cap=DIVERGENCE_CAP):
    """Roll the reference Lure system: x+ = Ax + Bu + B2*dzn(C2 x + D21 u).

    Stops early once the state passes ``cap``, the way the real diverging splits are
    recorded — they hold the approach to the escape, not the overflow after it.
    Returns ``(y, x, diverged)``.
    """
    n = len(u)
    x = np.asarray(x0, dtype=float).reshape(NX)
    y, xs = np.zeros((n, NE)), np.zeros((n, NX))
    for k in range(n):
        xs[k] = x
        uk = u[k].reshape(ND)
        z = ref["C2"] @ x + ref["D21"] @ uk
        w = z - np.clip(z, -1.0, 1.0)          # dead zone
        y[k] = ref["C"] @ x + ref["D"] @ uk + ref["D12"] @ w
        x = ref["A"] @ x + ref["B"] @ uk + ref["B2"] @ w
        if not np.isfinite(x).all() or np.abs(x).max() > cap:
            return y[: k + 1], xs[: k + 1], True
    return y, xs, False


def _converging_set(ref, n_traj, seed):
    """Ordinary trajectories: moderate input, non-zero x0, none of them escape.

    Returns (inputs, outputs, states) with the FULL state trajectory, matching what
    the CSV loader produces from state_col — the dataset asserts states and inputs
    share a sequence length.
    """
    rng = np.random.default_rng(seed)
    U, Y, X = [], [], []
    while len(U) < n_traj:
        u = CONV_AMP * rng.standard_normal((N_STEPS, ND))
        y, xs, diverged = _simulate(ref, u, X0_AMP * rng.standard_normal(NX))
        if diverged:
            continue                            # keep the converging split converging
        U.append(u); Y.append(y); X.append(xs)
    return np.stack(U), np.stack(Y), np.stack(X)


def _diverging_set(ref, n_traj, seed):
    """Trajectories that leave the safe region: larger input, x0 = 0, variable length.

    Mirrors the real ``*_div`` splits — recorded from rest until the state escapes,
    so they are ragged and are fed one per batch. Returns lists, not arrays.
    """
    rng = np.random.default_rng(seed)
    U, Y, X = [], [], []
    while len(U) < n_traj:
        u = DIV_AMP * rng.standard_normal((N_STEPS, ND))
        y, xs, diverged = _simulate(ref, u, np.zeros(NX))
        if not diverged or len(y) < 20:
            continue                            # keep the diverging split diverging
        U.append(u[: len(y)]); Y.append(y); X.append(xs)
    return U, Y, X


