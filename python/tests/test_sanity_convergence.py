def _model():
    return SimpleLure(nd=ND, ne=NE, nx=NX, nw=NW, activation=CFG.model.activation,
                      ts=TS, custom_params=CFG.model.custom_params)


def _warm_start(sanity, noise, seed=0):
    """A model warm-started from the reference, and the loaders it trains on."""
    tr_u, tr_y, tr_x = sanity["train"]
    va_u, va_y, va_x = sanity["val"]
    te_u, te_y, te_x = sanity["test"]
    tdu, tdy, tdx = sanity["train_div"]
    vdu, vdy, vdx = sanity["val_div"]
    tl, vl, tel, tdl, vdl, tedl, norm = create_dataloaders(
        train_inputs=tr_u, train_outputs=tr_y, train_states=tr_x,
        val_inputs=va_u, val_outputs=va_y, val_states=va_x,
        test_inputs=te_u, test_outputs=te_y, test_states=te_x,
        train_div_inputs=tdu, train_div_outputs=tdy, train_div_states=tdx,
        val_div_inputs=vdu, val_div_outputs=vdy, val_div_states=vdx,
        batch_size=CFG.data.batch_size, sequence_length=SEQ_LEN,
        sequence_stride=CFG.data.sequence_stride, normalize=CFG.data.normalize,
        normalization_method=CFG.data.normalization_method,
        shuffle=CFG.data.shuffle, num_workers=CFG.data.num_workers,
        diverging_batch_size=CFG.data.diverging_batch_size,
    )
    torch.manual_seed(0)
    m = _model()
    rep = m.initialize_parameters(
        tr_u, None, tr_y,
        init_config=replace(CFG.model.initialization, warm_start_path=str(sanity["path"]),
                            warm_start_noise=noise, warm_start_seed=seed),
        normalizer=norm,
    )
    return m, tl, vl, tel, tdl, vdl, norm, rep


def _val_loss(m, vl):
    loss_fn = get_loss_function("mse")
    total, n = 0.0, 0
    with torch.no_grad():
        for batch in vl:
            d, e = batch[0], batch[1]
            yh, _, _ = m(d, x0=None, warmup_steps=WARMUP)
            total += float(loss_fn(yh[:, WARMUP:, :], e[:, WARMUP:, :])); n += 1
    return total / max(n, 1)


# The two hyperparameters that decide whether the gate passes. BOTH differ from the
# Duffing configs, and both differences are findings rather than test-tuning — the
# config file explains each, and TestKnownCouplings pins them.
GATE_LR = CFG.optimizer.learning_rate
GATE_REG = CFG.training.regularization_weight
GATE_EPOCHS = CFG.training.max_epochs
GATE_CLIP = CFG.training.gradient_clip_value

# Every training run here is logged to MLflow so the gate is inspectable next to
# real runs — the loss curves and the distance-to-reference are the whole point of
# the check, and a pass/fail line does not show you those. Runs land in the local
# ./mlruns store (or MLFLOW_TRACKING_URI if set) under this experiment.
# Set SYSID_SANITY_MLFLOW=0 to turn it off, e.g. in CI.
MLFLOW_EXPERIMENT = CFG.mlflow.experiment_name


def _mlflow_enabled() -> bool:
    return os.environ.get("SYSID_SANITY_MLFLOW", "1") not in ("0", "false", "False")


@contextlib.contextmanager
def _mlflow_run(name, params):
    """An MLflow run for one training variant, or a no-op context when disabled.

    Never fails the test: a broken or unreachable tracking store makes the run a
    no-op rather than an error, because this is reporting, not the thing under test.
    """
    if not _mlflow_enabled():
        yield None
        return
    try:
        import mlflow
        mlflow.set_experiment(MLFLOW_EXPERIMENT)
        with mlflow.start_run(run_name=name):
            mlflow.set_tag("suite", "sanity_gate")
            mlflow.set_tag("variant", name)
            mlflow.log_params(params)
            yield mlflow
        return
    except Exception:  # reporting must never break the gate
        pass
    yield None


def _train(m, tl, vl, epochs, lr, tmp_path, div_loader=None, reg_weight=GATE_REG,
           mlf=None, val_fn=None, extra_fn=None):
    tr = Trainer(
        model=m, train_loader=tl, val_loader=vl, train_div_loader=div_loader,
        loss_fn=get_loss_function("mse"),
        optimizer=get_optimizer(m.parameters(), "adam", learning_rate=lr),
        regularization_weight=reg_weight, warmup_steps=WARMUP,
        gradient_clip_value=GATE_CLIP,
        solve_max_s_on_violation=True, device="cpu", mlflow_tracking=False,
        output_dir=str(tmp_path), model_dir=str(tmp_path), log_dir=str(tmp_path),
    )
    history = []
    for epoch in range(1, epochs + 1):
        stats = tr.train_epoch()
        val = (val_fn or _val_loss)(m, vl)
        history.append((stats["pred_loss"], val))
        if mlf is not None:
            mlf.log_metric("train_pred_loss", float(stats["pred_loss"]), step=epoch)
            mlf.log_metric("val_loss", float(val), step=epoch)
            if stats.get("pred_loss_div") is not None:
                mlf.log_metric("train_pred_loss_div", float(stats["pred_loss_div"]), step=epoch)
            mlf.log_metric("s", float(m.s), step=epoch)
            mlf.log_metric("feasible", float(m.check_constraints()), step=epoch)
            for name, value in (extra_fn() if extra_fn else {}).items():
                mlf.log_metric(name, float(value), step=epoch)
    return history


