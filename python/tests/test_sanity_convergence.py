class TestKnownCouplings:
    """Why the gate runs at lr=5e-5 and reg_weight=1e-5 rather than the Duffing
    configs' 5e-3 / 1e-3. Both are documented as tests so they are not rediscovered.

    These assert that a KNOWN LIMITATION still bites. If someone makes the training
    loop robust to either (gradient normalization, per-parameter scaling, a trust
    region, scaling the barrier by the prediction loss) these start failing — that
    is a fix, not a regression: delete the test and relax the gate's setting.
    """

    def test_a_large_lr_destroys_a_near_perfect_start(
        self, sanity, true_theta_loss, tmp_path
    ):
        """Adam's step is ~lr per element regardless of that element's magnitude.
        Here B entries are ~5e-3 and rho(A) is 0.95, so lr=5e-3 is a 100% change to
        B and enough to move A a long way; the rollout then leaves the region where
        the linearization is meaningful and the loss explodes."""
        m, tl, vl, _, _, _, _, _ = _warm_start(sanity, noise=0.002)
        with _mlflow_run("large_lr", {"variant": "large_lr", "lr": 5e-3,
                                      "regularization_weight": GATE_REG,
                                      "warm_start_noise": 0.002, "epochs": 5}) as mlf:
            history = _train(m, tl, vl, epochs=5, lr=5e-3, tmp_path=tmp_path, mlf=mlf)
            best = min(v for _, v in history)
            if mlf is not None:
                mlf.log_metric("best_val_loss", best)
                mlf.log_metric("true_theta_loss", true_theta_loss)
        assert best > 10 * true_theta_loss, (
            f"lr=5e-3 now recovers the warm start (best val_loss {best:.4g} vs "
            f"true-theta {true_theta_loss:.4g}). If the training loop was made "
            f"robust to the step size, delete this test and relax GATE_LR."
        )

    def test_the_barrier_weight_dominates_near_the_optimum(
        self, sanity, true_theta_loss, gate_run, tmp_path
    ):
        """The barrier is O(100) while pred_loss near the optimum is O(1e-4), so at
        reg_weight=1e-3 it contributes ~600x the prediction loss and the optimizer
        minimizes the barrier instead of the fit. The certificate still needs a
        barrier — at weight 0 the run ends INFEASIBLE — so the weight has to be
        scaled against the prediction loss, not fixed."""
        m, tl, vl, _, _, _, _, _ = _warm_start(sanity, noise=0.002)
        barrier = float(m.get_regularization_loss())
        pred = _val_loss(m, vl)
        assert 1e-3 * barrier > 100 * pred, (
            f"the barrier no longer dominates at reg_weight=1e-3 "
            f"(barrier {barrier:.4g}, pred {pred:.4g})"
        )
        with _mlflow_run("large_reg", {"variant": "large_reg", "lr": GATE_LR,
                                       "regularization_weight": 1e-3,
                                       "warm_start_noise": 0.002,
                                       "epochs": GATE_EPOCHS}) as mlf:
            history = _train(m, tl, vl, epochs=GATE_EPOCHS, lr=GATE_LR,
                             tmp_path=tmp_path, reg_weight=1e-3, mlf=mlf)
            best = min(v for _, v in history)
            if mlf is not None:
                mlf.log_metric("best_val_loss", best)
                mlf.log_metric("true_theta_loss", true_theta_loss)
        gate_best = min(v for _, v in gate_run["history"])
        assert best > 2.0 * gate_best, (
            f"reg_weight=1e-3 is no longer worse than the gate's {GATE_REG:g} "
            f"(best val_loss {best:.4g} vs {gate_best:.4g}). If the barrier is now "
            f"scaled relative to the prediction loss, delete this test and relax "
            f"GATE_REG."
        )


