"""THE SANITY GATE: a warm-started model must converge back to the model that
generated the data.

This is a slow end-to-end test, closer to ``test_scripts_smoke`` than to a unit
test, and it is deliberately the strongest statement in the suite:

    Data is generated by a known Lure system. The model is initialized AT that
    system, perturbed slightly, and projected back onto the certified set. A few
    epochs of training must then drive the prediction loss back down to the level
    the generating parameters themselves achieve.

If that fails, the training loop is wrong — not the initialization, not the model
class, not the data. There is nothing left to blame: the optimum is known, it is
representable, and the run starts next to it.

Hermetic: the reference system and the .npz are built here, so the test does not
depend on ~/genSecSysId-Data. Its settings come from the checked-in
``tests/resoruces/sanity_gate.yaml`` — deliberately NOT the working config, which
is a live experiment; the gate has to be a fixed reference point. That file also
carries the reasoning for the two hyperparameters that differ from the Duffing
configs.

Every training run is logged to MLflow under the ``crnn-sanity_gate`` experiment —
the gate itself plus the two known-limitation variants — so the loss curves and the
distance-to-reference are inspectable next to real runs instead of collapsing to a
pass/fail line. The ``gate`` run carries ``gate_passed`` and ``best_over_true``.
Set ``SYSID_SANITY_MLFLOW=0`` to disable (e.g. in CI).

Note on the learning rate. This runs at a much smaller lr than the Duffing configs
use, and that is a real finding rather than test-tuning: Adam's step is ~lr per
element regardless of that element's scale, so with B entries ~5e-3 and rho(A)
within ~6e-3 of the unit circle, an lr of 5e-3 moves A straight out of the stable
region on the first step and the rollout explodes. See TestLearningRateSensitivity.
"""

