r"""Generate a starter config for a prepared benchmark.

Everything the DATA determines is filled in from the prepared dataset and a
balanced linear fit of it; everything that is a modelling choice is left
explicit in the emitted YAML with the reasoning attached.

The initialization follows :mod:`sysid.models.linear_init`:

1. fit a balanced linear model of order ``nx`` on the NORMALIZED training data
   and write ``A.npy``/``B.npy``/``C.npy`` beside the dataset;
2. set ``alpha_0`` just above ``rho(A)``, because the Lyapunov condition needs
   ``rho(A) < alpha`` and nothing else pins alpha;
3. bisect the loop gain scaling ``B2``/``C2``. ``gain = 0`` opens the Lur'e loop
   and is feasible whenever ``A`` is Schur under alpha, so the bisection always
   terminates -- this is what replaces sweeping ``B2`` over decades.
"""

import logging
from pathlib import Path
from typing import Optional

import numpy as np

logger = logging.getLogger(__name__)

#: Requested loop gain. The bisection only ever reduces it.
DEFAULT_B2C2 = 0.1
#: Learning rate. Larger than the 5e-5 the hand-built inits needed, which is the
#: point of starting from a conditioned realization.
DEFAULT_LEARNING_RATE = 1.0e-3

CONFIG_TEMPLATE = """\
# {name} -- regional certificate, generated by scripts/prepare_benchmark.py.
#
# Prepare the data first:
#
#   python scripts/prepare_benchmark.py --benchmark {name}
#
# GENERATED. The values below that the DATA determines are filled in; the ones
# that are a modelling choice are called out. Re-running the generator
# overwrites this file, so put lasting edits somewhere else.
#
{notes_block}#
# INITIALIZATION. A, B and C are a BALANCED linear model identified from the
# training data (subspace ID + balanced truncation, sysid.models.linear_init),
# not a random draw. Balancing is what makes a single B2/C2 magnitude mean the
# same thing in every state direction; without it the loop gain varies wildly
# across modes and B2 has to be found by sweeping.
#
#   rho(A)            = {rho:.6f}   (alpha_0 must exceed this)
#   state RMS spread  = {spread:.2f}   (1 is perfectly balanced)
#   Hankel energy kept= {energy:.1%}   at nx = {nx}
#   linear-only NRMSE = {nrmse}   (the Lur'e model should beat this)
#
# B2/C2 LOOP GAIN. Requested {requested}; bisection accepted {achieved}
# ({gain_note}).
{floor_block}
data:
  train_path: "{train_path}"
  input_col: [{input_cols}]
  output_col: [{output_cols}]
  pattern: "*.csv"
  normalize: true
  normalization_method: "scale_only"
  batch_size: {batch_size}
  # {n_records} training record(s) of {record_length} samples.
  train_sequence_length: {seq_len}
  sequence_stride: {seq_len}
  shuffle: true
  num_workers: 0
  sampling_time: {sampling_time}
  # None of these benchmarks ships diverging trajectories.
  use_diverging_trajectories: false

model:
  model_type: "crnn"
  nw: {nw}
  # MODELLING CHOICE. {nx_note}
  nx: {nx}
  activation: "dzn"
  custom_params:
    learn_L: true
    freeze_alpha: false
    # Just above rho(A) so the Lyapunov condition has room. Raising it further
    # shrinks sigma(U) = |s|*sqrt(1 - alpha^2) for nothing.
    alpha_0: {alpha_0}
    identity_init:
      A:   {{load_from: "{init_dir}/A.npy"}}
      B:   {{load_from: "{init_dir}/B.npy"}}
      C:   {{load_from: "{init_dir}/C.npy"}}
      B2:  {{std: {b2}}}
      C2:  {{std: {c2}}}
      # Effectively a no-op: when the identity draw leaves the LMI infeasible,
      # initialization falls back to the MaxS solve over (D21, P, L, s), which
      # overwrites D21.
      D21: {{std: 0.5}}
    structural_constraints:
      D12:
        fixed: true
        value: 0.0

  initialization:
    method: identity

optimizer:
  optimizer_type: "adam"
  learning_rate: {learning_rate}
  use_scheduler: true
  scheduler_type: "reduce_on_plateau"
  scheduler_patience: 20
  scheduler_factor: 0.25

training:
  max_epochs: 100
  gradient_clip_value: 1.0
  loss_type: "mse"
  use_custom_regularization: true
  regularization_weight: 1.0e-2
  min_regularization_weight: 1.0e-7
  decay_regularization_weight: true
  regularization_decay_factor: 0.1
  device: "cpu"
  log_gradients: true
  # The trainer rolls out from x0 = 0 while each window starts mid-trajectory.
  # {warmup_note}
  warmup_steps: {warmup}
  input_regularization_weight: 0.0
  activity_regularization_weight: 0.0
  h_regularization_weight: 0.0

  # Nothing but this pushes s up -- the log-det barrier only ever pushes it down.
  max_s_trigger: on_violation
  max_s_every: 1

mlflow:
  tracking_uri: null
  experiment_name: "crnn-{slug}"
  run_name: "regional"
  log_models: true
  log_artifacts: true

evaluation:
  metrics:
    - rmse
    - nrmse

root_dir: "~/genSecSysId-Data"
seed: 42
log_level: "INFO"
"""


def _wrap(text: str, width: int = 76, prefix: str = "# ") -> str:
    import textwrap

    if not text:
        return ""
    return "\n".join(prefix + line for line in textwrap.wrap(text, width)) + "\n"


def choose_sequence_length(record_length: int, warmup: int, cap: int = 2048) -> int:
    """A window that fits the record and leaves something to score after warmup."""
    target = min(cap, record_length)
    if target <= warmup:
        # Never leave the loss with an empty window (trainer slices [warmup:]).
        target = min(record_length, max(warmup * 4, warmup + 16))
    return int(target)


def render_config(
    spec,
    dataset_dir: Path,
    init_dir: Path,
    linear,
    alpha_0: float,
    b2c2: float,
    requested_b2c2: float,
    sampling_time: Optional[float],
    n_records: int,
    record_length: int,
    input_floor: Optional[float] = None,
    s_at_gain: Optional[float] = None,
    learning_rate: float = DEFAULT_LEARNING_RATE,
) -> str:
    """Fill :data:`CONFIG_TEMPLATE` for one prepared benchmark."""
    warmup = max(spec.init_window or 0, 50)
    seq_len = choose_sequence_length(record_length, warmup)
    at_request = abs(b2c2 - requested_b2c2) < 1e-12

    gain_note = (
        "the requested value was feasible as-is"
        if at_request
        else "reduced: the LMI or the input floor did not admit the requested value"
    )
    floor_block = ""
    if input_floor is not None and s_at_gain is not None:
        admits = s_at_gain >= input_floor
        floor_block = _wrap(
            f"INPUT FLOOR. s >= max_k||u_k|| = {input_floor:.3f} is forced by the input "
            f"condition regardless of P. At the accepted gain MaxS gives s = "
            f"{s_at_gain:.3f}, which "
            + ("admits the training inputs." if admits else
               "does NOT admit them -- expect MaxS to go infeasible during training. "
               "Lower B2/C2 to trade nonlinearity for a larger certified set.")
        )

    nx_note = (
        f"nx = {spec.default_nx} keeps {linear.energy_retained:.1%} of the Hankel "
        "energy; raise it if the linear NRMSE above is poor."
    )
    return CONFIG_TEMPLATE.format(
        name=spec.name,
        slug=spec.name.lower().replace("_", "-"),
        notes_block=_wrap(spec.notes) + ("#\n" if spec.notes else ""),
        rho=linear.rho,
        spread=linear.state_rms_spread,
        energy=linear.energy_retained,
        nrmse=np.array2string(np.asarray(linear.nrmse), precision=3),
        nx=spec.default_nx,
        nw=spec.default_nw,
        nx_note=nx_note,
        requested=f"{requested_b2c2:g}",
        achieved=f"{b2c2:g}",
        gain_note=gain_note,
        floor_block=floor_block,
        train_path=str(dataset_dir).replace(str(Path.home()), "~"),
        init_dir=str(init_dir).replace(str(Path.home()), "~"),
        input_cols=", ".join(f'"{c}"' for c in spec.input_cols),
        output_cols=", ".join(f'"{c}"' for c in spec.output_cols),
        batch_size=8 if n_records < 32 else 32,
        n_records=n_records,
        record_length=record_length,
        seq_len=seq_len,
        sampling_time=sampling_time if sampling_time is not None else 1.0,
        alpha_0=f"{alpha_0:.6f}",
        b2=f"{b2c2:g}",
        c2=f"{b2c2:g}",
        learning_rate=f"{learning_rate:g}",
        warmup=warmup,
        warmup_note=(
            f"The benchmark's own state-initialization window is "
            f"{spec.init_window}; this is raised because we start from x0 = 0."
            if spec.init_window else
            "The benchmark states no washout length, so this is a default."
        ),
    )


SWEEP_TEMPLATE = """\
# Sweep definition for {name} -- the three certificate arms.
#
# Submit with:
#   cd ~/01_git/genSecSysId/python
#   bash slurm/submit_sweep.sh {sweep_path}
#
# GENERATED by scripts/prepare_benchmark.py. Tasks = {n_groups} groups x
# {n_seeds} seeds = {total} array entries.
#
# The groups are CONCATENATED, not multiplied: model.custom_params.learn_L is
# meaningless when use_custom_regularization is false, so putting it in one
# cartesian product would generate duplicate NoSec runs.
#
# B2/C2 come from the base config, where the loop gain was sized against this
# dataset's input floor ({b2c2:g}). Overriding them here is what a sensitivity
# sweep would do -- see the commented block at the end.

sweep_name: {name}

base_config: {base_config}

n_seeds: {n_seeds}

search_space:
  # NoSec -- no barrier, no certificate. learn_L is deliberately absent.
  - training.use_custom_regularization: [false]
    optimizer.learning_rate: [{learning_rate:g}]
  # GenSec -- regional certificate, L learnable so H = L P^-1 is nonzero.
  - training.use_custom_regularization: [true]
    optimizer.learning_rate: [{learning_rate:g}]
    model.custom_params.learn_L: [true]
  # StdSec -- global sector condition, L fixed at zero.
  - training.use_custom_regularization: [true]
    optimizer.learning_rate: [{learning_rate:g}]
    model.custom_params.learn_L: [false]

# To sweep the loop gain as well, replace a group's body with e.g.:
#   model.custom_params.identity_init.B2: [{{std: {b2c2:g}}}, {{std: {b2c2_low:g}}}]
#   model.custom_params.identity_init.C2: [{{std: {b2c2:g}}}, {{std: {b2c2_low:g}}}]
# Note each extra list MULTIPLIES that group's task count.
"""


def render_sweep(
    spec,
    base_config: str,
    b2c2: float,
    learning_rate: float = DEFAULT_LEARNING_RATE,
    n_seeds: int = 3,
    sweep_path: str = "configs/sweep_<name>.yaml",
) -> str:
    """The three-arm sweep file for one benchmark.

    The arms are exactly the comparison this project is about: NoSec (no
    barrier), GenSec (regional, ``learn_L: true``) and StdSec (global,
    ``learn_L: false``).
    """
    n_groups = 3
    return SWEEP_TEMPLATE.format(
        name=spec.name,
        base_config=base_config,
        n_seeds=n_seeds,
        n_groups=n_groups,
        total=n_groups * n_seeds,
        learning_rate=learning_rate,
        b2c2=b2c2,
        b2c2_low=b2c2 / 10.0,
        sweep_path=sweep_path,
    )
